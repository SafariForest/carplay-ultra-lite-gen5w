#!/usr/bin/env python3
"""Writes mod/src/ioniq6/cpclimate/VsData.java from data/vs-*.opack and data/vs-meta.txt
(exported from LIVI's own vehicle_state code by data/vsdump-src: vsdump --climate --export data).
The data goes into the hooks jar because a mod's other files aren't always readable by DiPO.

usage: mkvsdata.py"""
import base64
from pathlib import Path

R = Path(__file__).resolve().parents[1]
D = R / "data"
OUT = R / "mod/src/ioniq6/cpclimate/VsData.java"


def chunks(b):
    s = base64.b64encode(b).decode()
    return [s[i:i + 30000] for i in range(0, len(s), 30000)]   # constant pool strings: < 65535 bytes each


def strings(name, b):
    parts = ",\n            ".join('"%s"' % c for c in chunks(b))
    return f"    static final String[] {name} = {{\n            {parts} }};\n"


meta = dict(l.split(" ", 1) if " " in l else (l, "") for l in (D / "vs-meta.txt").read_text().splitlines() if l)
writable = [int(x) for x in meta.get("writable", "").split()]
controls = [x.split("=", 1) for x in meta.get("controls", "").split()]
shared = [int(x) for x in meta.get("shared", "").split()]
notifiers = [x.split("=", 1) for x in meta.get("notifiers", "").split()]
names = [x.split("=", 1) for x in meta.get("names", "").split()]

OUT.write_text(f"""package ioniq6.cpclimate;

/**
 * Generated by tools/mkvsdata.py from LIVI's vehicle state description (data/vs-*): do not edit.
 * The accessory list (configResponse) and the initial values, as LIVI's own OPACK, the iids the
 * phone may write (and which of them the car writes too), the large values' notifiers, every
 * characteristic's name, and the controls. Based on LIVI by Lasse Heitgres (https://github.com/f-io/LIVI).
 */
final class VsData {{
{strings("ACCESSORIES", (D / "vs-accessories.opack").read_bytes())}
{strings("VALUES", (D / "vs-values.opack").read_bytes())}
    static final int[] WRITABLE = {{ {", ".join(map(str, writable))} }};

    static final int[] SHARED = {{ {", ".join(map(str, shared))} }};

    /** iid, then the iid counting its changes */
    static final int[] NOTIFIERS = {{ {", ".join(i + ", " + n for i, n in notifiers)} }};

    static final int[] NAME_IIDS = {{ {", ".join(i for i, _ in names)} }};
    static final String[] NAMES = {{ {", ".join('"%s"' % n for _, n in names)} }};

    static final int[] CONTROL_IIDS = {{ {", ".join(i for i, _ in controls)} }};
    static final String[] CONTROL_NAMES = {{ {", ".join('"%s"' % n for _, n in controls)} }};

    static byte[] bytes(String[] parts) {{
        StringBuilder s = new StringBuilder();
        for (String p : parts) s.append(p);
        return base64(s.toString());
    }}

    /** plain base64 (Android 4.4 has android.util.Base64, the host tests don't) */
    static byte[] base64(String s) {{
        String a = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
        int pad = s.endsWith("==") ? 2 : s.endsWith("=") ? 1 : 0;
        byte[] out = new byte[s.length() / 4 * 3 - pad];
        int o = 0;
        for (int i = 0; i < s.length(); i += 4) {{
            int v = 0;
            for (int j = 0; j < 4; j++) {{
                char c = s.charAt(i + j);
                v = v << 6 | (c == '=' ? 0 : a.indexOf(c));
            }}
            for (int j = 2; j >= 0; j--) if (o + 2 - j < out.length) out[o + 2 - j] = (byte) (v >> (8 * j));
            o += 3;
        }}
        return out;
    }}
}}
""")
print(OUT, len(writable), "writable,", len(shared), "shared,", len(names), "names,", len(controls), "controls")
