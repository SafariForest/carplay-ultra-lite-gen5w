"""LIVI's extra HID devices (livi-cp hid.rs: knob, media, telephony on the main display, a knob on the
cluster) as a binary plist array, for the native hook (native/livi_hid.h). usage: mklivihid.py <out.h>"""
import plistlib, sys
KNOB = bytes([0x05,0x01,0x09,0x08,0xa1,0x01,0x05,0x09,0x09,0x01,0x15,0x00,0x25,0x01,0x75,0x01,
    0x95,0x01,0x81,0x02,0x05,0x0c,0x0a,0x23,0x02,0x0a,0x24,0x02,0x95,0x02,0x81,0x02,
    0x95,0x05,0x81,0x01,0x05,0x01,0x09,0x01,0xa1,0x00,0x09,0x30,0x09,0x31,0x15,0x81,
    0x25,0x7f,0x75,0x08,0x95,0x02,0x81,0x02,0xc0,0x09,0x38,0x15,0x81,0x25,0x7f,0x75,
    0x08,0x95,0x01,0x81,0x06,0xc0])
MEDIA = bytes([0x05,0x0c,0x09,0x01,0xa1,0x01,0x15,0x00,0x25,0x06,0x05,0x0c,0x0a,0x00,0x00,0x0a,
    0xb0,0x00,0x0a,0xb1,0x00,0x0a,0xcd,0x00,0x0a,0xb5,0x00,0x0a,0xb6,0x00,0x0a,0x9e,
    0x02,0x75,0x08,0x95,0x01,0x81,0x00,0xc0])
TELEPHONY = bytes([0x05,0x0b,0x09,0x07,0xa1,0x01,0x15,0x00,0x25,0x11,0x05,0x0b,0x09,0x00,0x09,0x20,
    0x09,0x21,0x09,0x26,0x09,0x2f,0x09,0xb0,0x09,0xb1,0x09,0xb2,0x09,0xb3,0x09,0xb4,
    0x09,0xb5,0x09,0xb6,0x09,0xb7,0x09,0xb8,0x09,0xb9,0x09,0xba,0x09,0xbb,0x05,0x07,
    0x09,0x2a,0x75,0x08,0x95,0x01,0x81,0x00,0xc0])
def dev(uid, name, desc, display):
    return {"hidProductID": 1, "hidVendorID": 2, "hidCountryCode": 0, "uuid": "%x" % uid,
            "name": name, "displayUUID": display, "hidDescriptor": desc}
devices = [dev(0x2a2a2a2b, "Ioniq 6 Knob", KNOB, "Center_Display"),
           dev(0x2a2a2a2c, "Ioniq 6 Media", MEDIA, "Center_Display"),
           dev(0x2a2a2a2d, "Ioniq 6 Telephony", TELEPHONY, "Center_Display"),
           dev(0x2a2a2a2e, "Ioniq 6 Cluster Knob", KNOB, "Cluster_Display")]
b = plistlib.dumps(devices, fmt=plistlib.FMT_BINARY, sort_keys=True)
with open(sys.argv[1], "w") as f:
    f.write("/* generated by tools/mklivihid.py: LIVI hid.rs knob, media, telephony and cluster knob devices */\n")
    f.write("static const unsigned char livi_hid[%d] = {\n" % len(b))
    for i in range(0, len(b), 16):
        f.write("    " + ", ".join("0x%02x" % x for x in b[i:i + 16]) + ",\n")
    f.write("};\n")
print(len(b), "bytes")
